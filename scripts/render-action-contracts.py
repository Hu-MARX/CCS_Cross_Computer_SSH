"""Regenerate the reference from the same packaged contracts used at runtime."""
from pathlib import Path
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
from ccs.contracts import describe


def fields(schema, prefix='', required=False, definitions=None):
    definitions = definitions or schema.get('$defs', {})
    if '$ref' in schema:
        yield from fields(definitions[schema['$ref'].split('/')[-1]], prefix, required, definitions)
        return
    variants = schema.get('oneOf') or schema.get('anyOf')
    if variants:
        for index, variant in enumerate(variants):
            if variant.get('type') == 'null':
                yield (prefix or '(root)', 'optional null', 'null', '')
                continue
            label = variant.get('properties', {}).get(schema.get('x-discriminator'), {}).get('const')
            variant_prefix = prefix + (f' [{label}]' if label else '')
            yield from fields(variant, variant_prefix, required, definitions)
        return
    properties = schema.get('properties')
    if properties:
        for name, child in properties.items():
            path = prefix + '.' + name if prefix else name
            yield from fields(child, path, name in schema.get('required', []), definitions)
        if schema.get('additionalProperties'):
            yield (prefix + '.*' if prefix else '*', 'optional', 'metadata', 'additional fields permitted')
        return
    kind = schema.get('type', 'JSON')
    if isinstance(kind, list):
        kind = '/'.join(kind)
    limits = []
    for keyword in ('const', 'enum', 'minimum', 'maximum', 'exclusiveMinimum', 'minLength', 'maxLength', 'minItems', 'maxItems', 'default'):
        if keyword in schema:
            limits.append(keyword + '=' + json.dumps(schema[keyword], ensure_ascii=False))
    if 'pattern' in schema:
        limits.append('format=' + schema['pattern'])
    yield (prefix or '(root)', 'required' if required else 'optional', str(kind), '; '.join(limits))
    if schema.get('type') == 'array':
        yield from fields(schema.get('items', {}), prefix + '[]', False, definitions)


def table(schema):
    rows = ['| Field | Presence | Type | Constraints |', '| --- | --- | --- | --- |']
    for row in fields(schema):
        escaped = [item.replace('|', '\\|').replace('\n', '\\n') for item in row]
        rows.append('| ' + ' | '.join(escaped) + ' |')
    return '\n'.join(rows)


def render():
    catalog = describe()
    lines = [
        '# CCS Action Contracts', '',
        'Generated by `python scripts/render-action-contracts.py` from the packaged canonical resource '
        '`src/ccs/resources/action-contracts.json`. Change the resource and regenerate; CLI, gateway validation, '
        'SDK and MCP contract queries use this same source.', '',
        '## Offline access', '',
        '```console', 'ccsctl describe', 'ccsctl describe --action run.submit',
        'ccsctl describe --action workspace.execute --workspace-action stage',
        'ccsctl describe --schema request', '```', '',
        '`gateway.describe` is also a local-only read action with optional `action` and `workspace_action` payload fields. '
        'It works without host configuration, databases, SSH or network. SDK callers can use `CCSClient.describe()`; '
        'MCP callers can use `ccs_read(action="gateway.describe", payload={"action":"run.submit"})`.', '',
        'Input and output schemas returned by describe are self-contained JSON Schema 2020-12 documents with local references. '
        'The three published schemas are generated by `ccs.contracts.request_schema()`, `result_schema()` and '
        '`experiment_spec_schema()`; runtime schema lookup needs only the installed package resource.', '',
        '## Compatibility and errors', '',
    ]
    lines += [f'- **{name}**: {value}' for name, value in catalog['compatibility'].items()]
    lines += ['', 'All documented valid requests keep their existing meanings. Unknown fields on action payloads and workspace '
              'requests, missing required fields and illegal types now fail before compatibility checks or remote calls. '
              'Booleans are not accepted as integers. Unknown fields that were previously ignored no longer silently succeed; '
              'use the selected contract to remove them. ExperimentSpec metadata scopes remain extensible.', '',
              'Contract failures include `code`, `message`, `retryable=false`, `execution_state="not_sent"` and `field_errors` '
              'with exact paths, stable field codes and descriptions. Values are omitted from error descriptions.', '',
              '```json', json.dumps({'code': 'INVALID_REQUEST', 'message': 'payload violates its action contract',
                                    'retryable': False, 'execution_state': 'not_sent',
                                    'field_errors': [{'path': 'payload.spec.command.argv', 'code': 'required',
                                                      'message': 'required field is missing'}]}, indent=2), '```', '',
              'Mutation classification still requires the existing dry-run and exact gateway confirmation. The workspace '
              '`plan_sha256`/`applied_sha256` fields identify a staged worker change and are separate from '
              '`confirm_plan_sha256` in the gateway request envelope. A matching hash is not authentication or proof of user approval.', '',
              'Output schemas describe `result` after execution. A dry-run result may be null or a worker plan. '
              'Worker diagnostics and snapshots have optional fields because legacy/Fake workers and new workers expose different facts; '
              'absence does not imply zero or healthy state. Metadata extension fields may be added by adapters.', '',
              '## Actions', '']
    for name, contract in catalog['actions'].items():
        lines += ['### ' + name, '', '**Classification:** ' + contract['classification'] + '. ' + contract['summary'], '',
                  '**Input fields (`payload`)**', '', table(contract['input_schema']), '',
                  '**Output fields (`result`)**', '', table(contract['output_schema']), '', '**Examples (payload only)**', '',
                  '```json', json.dumps(contract['examples'], ensure_ascii=False, indent=2), '```', '']
        if contract['constraints']:
            lines += ['**Execution constraints**', ''] + ['- ' + item for item in contract['constraints']] + ['']
        for subaction, nested in contract.get('workspace_actions', {}).items():
            lines += ['#### workspace.execute / ' + subaction, '', '**Classification:** ' + nested['classification'], '',
                      '**Input fields (`payload`)**', '', table(nested['input_schema']), '',
                      '**Output fields (`result`)**', '', table(nested['output_schema']), '', '**Examples (payload only)**', '',
                      '```json', json.dumps(nested['examples'], ensure_ascii=False, indent=2), '```', '',
                      '**Execution constraints**', ''] + ['- ' + item for item in nested['constraints']] + ['']
    return '\n'.join(lines).rstrip() + '\n'


if __name__ == '__main__':
    destination = ROOT / 'docs' / 'ACTION-CONTRACTS.md'
    destination.write_text(render(), encoding='utf-8', newline='\n')
    print(destination)
